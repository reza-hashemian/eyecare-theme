def apply_alacritty(t):
    """Alacritty: >=0.13 uses TOML, <=0.12 uses YAML. Detect by version and existing file."""
    if not which("alacritty") and not (HOME/".config"/"alacritty").exists():
        return False, "not installed"
    rc, out, _ = run(["alacritty", "--version"]) if which("alacritty") else (1, "", "")
    ver = (0, 0)
    m = re.search(r"(\d+)\.(\d+)", out)
    if m: ver = (int(m.group(1)), int(m.group(2)))

    base = HOME / ".config" / "alacritty"
    if MAC: base = HOME / ".config" / "alacritty"
    if WIN: base = Path(os.environ.get("APPDATA", HOME)) / "alacritty"

    p = t["palette"]
    use_toml = ver >= (0, 13) or (base/"alacritty.toml").exists()
    if use_toml:
        theme_file = base / "eyecare-theme.toml"
        body = f'''# generated by eyecare-theme -- {t["name"]}
[colors.primary]
background = "{t['bg']}"
foreground = "{t['fg']}"

[colors.cursor]
text = "{t['bg']}"
cursor = "{t['cursor']}"

[colors.selection]
text = "{t['selection_fg']}"
background = "{t['selection_bg']}"

[colors.normal]
black = "{p[0]}"
red = "{p[1]}"
green = "{p[2]}"
yellow = "{p[3]}"
blue = "{p[4]}"
magenta = "{p[5]}"
cyan = "{p[6]}"
white = "{p[7]}"

[colors.bright]
black = "{p[8]}"
red = "{p[9]}"
green = "{p[10]}"
yellow = "{p[11]}"
blue = "{p[12]}"
magenta = "{p[13]}"
cyan = "{p[14]}"
white = "{p[15]}"
'''
        _write(theme_file, body)
        main = base / "alacritty.toml"
        cur = main.read_text(encoding="utf-8") if main.exists() else ""
        imp = 'import = ["' + str(theme_file).replace("\\", "/") + '"]'
        if "eyecare-theme.toml" not in cur:
            if re.search(r"^\s*(general\.)?import\s*=", cur, re.M):
                cur = re.sub(r'^(\s*(?:general\.)?import\s*=\s*\[)',
                             r'\1"' + str(theme_file).replace("\\", "/") + '", ', cur, count=1, flags=re.M)
            else:
                cur = imp + "\n" + cur
            _write(main, cur)
        return True, f"alacritty (toml) -> {theme_file.name}"
    else:
        theme_file = base / "eyecare-theme.yml"
        body = f'''# generated by eyecare-theme -- {t["name"]}
colors:
  primary:
    background: '{t['bg']}'
    foreground: '{t['fg']}'
  cursor:
    text: '{t['bg']}'
    cursor: '{t['cursor']}'
  selection:
    text: '{t['selection_fg']}'
    background: '{t['selection_bg']}'
  normal:
    black:   '{p[0]}'
    red:     '{p[1]}'
    green:   '{p[2]}'
    yellow:  '{p[3]}'
    blue:    '{p[4]}'
    magenta: '{p[5]}'
    cyan:    '{p[6]}'
    white:   '{p[7]}'
  bright:
    black:   '{p[8]}'
    red:     '{p[9]}'
    green:   '{p[10]}'
    yellow:  '{p[11]}'
    blue:    '{p[12]}'
    magenta: '{p[13]}'
    cyan:    '{p[14]}'
    white:   '{p[15]}'
'''
        _write(theme_file, body)
        main = base / "alacritty.yml"
        cur = main.read_text(encoding="utf-8") if main.exists() else ""
        # yaml: replace any existing top-level colors: block with an import
        if "eyecare-theme.yml" not in cur:
            cur = re.sub(r"^colors:\n(?:[ \t]+.*\n|\n)*", "", cur, flags=re.M)
            if re.search(r"^import:", cur, re.M):
                cur = re.sub(r"^(import:\s*\n)", r"\1  - " + str(theme_file) + "\n", cur, count=1, flags=re.M)
            else:
                cur = "import:\n  - " + str(theme_file) + "\n" + cur
            _write(main, cur)
        return True, f"alacritty (yaml) -> {theme_file.name}"

def apply_kitty(t):
    base = HOME/".config"/"kitty"
    if MAC: base = HOME/"Library"/"Preferences"/"kitty"
    if not which("kitty") and not base.exists():
        return False, "not installed"
    p = t["palette"]
    lines = [f"# generated by eyecare-theme -- {t['name']}",
             f"background {t['bg']}", f"foreground {t['fg']}",
             f"cursor {t['cursor']}", f"cursor_text_color {t['bg']}",
             f"selection_background {t['selection_bg']}",
             f"selection_foreground {t['selection_fg']}"]
    for i, c in enumerate(p):
        lines.append(f"color{i} {c}")
    theme_file = base / "eyecare-theme.conf"
    _write(theme_file, "\n".join(lines) + "\n")
    main = base / "kitty.conf"
    cur = main.read_text(encoding="utf-8") if main.exists() else ""
    if "eyecare-theme.conf" not in cur:
        _write(main, cur.rstrip() + "\n\ninclude eyecare-theme.conf\n")
    # live reload all running instances
    run(["kitty", "@", "--to", os.environ.get("KITTY_LISTEN_ON", ""), "set-colors", "-a", str(theme_file)])
    return True, "kitty -> eyecare-theme.conf"

