import json, os, re, sys, glob
from pathlib import Path
from core import run, which, backup, hex_to_rgb

HOME = Path.home()
WIN = sys.platform == "win32"
MAC = sys.platform == "darwin"

def _write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    backup(path)
    path.write_text(text, encoding="utf-8")

def _read_json_lenient(path: Path):
    """Read JSON allowing // and /* */ comments and trailing commas (VS Code style)."""
    if not path.exists():
        return {}
    txt = path.read_text(encoding="utf-8")
    if not txt.strip():
        return {}
    try:
        return json.loads(txt)
    except Exception:
        pass
    # strip comments outside strings
    out, i, n, instr, esc = [], 0, len(txt), False, False
    while i < n:
        c = txt[i]
        if instr:
            out.append(c)
            if esc: esc = False
            elif c == "\\": esc = True
            elif c == '"': instr = False
            i += 1
            continue
        if c == '"':
            instr = True; out.append(c); i += 1; continue
        if c == "/" and i + 1 < n and txt[i+1] == "/":
            while i < n and txt[i] != "\n": i += 1
            continue
        if c == "/" and i + 1 < n and txt[i+1] == "*":
            i += 2
            while i + 1 < n and not (txt[i] == "*" and txt[i+1] == "/"): i += 1
            i += 2
            continue
        out.append(c); i += 1
    cleaned = re.sub(r",(\s*[}\]])", r"\1", "".join(out))
    return json.loads(cleaned)

