def _jetbrains_config_roots():
    if WIN:
        base = Path(os.environ.get("APPDATA", HOME))/"JetBrains"
    elif MAC:
        base = HOME/"Library"/"Application Support"/"JetBrains"
    else:
        base = Path(os.environ.get("XDG_CONFIG_HOME", HOME/".config"))/"JetBrains"
    if not base.exists():
        return []
    roots = []
    for d in sorted(base.iterdir()):
        if d.is_dir() and any(d.name.startswith(p) for p in _JB_DIRS):
            roots.append(d)
    return roots

def apply_jetbrains(t):
    roots = _jetbrains_config_roots()
    if not roots:
        return False, "not installed"
    msgs, any_ok = [], False
    for root in roots:
        opts = root / "options"
        opts.mkdir(parents=True, exist_ok=True)
        # 1) editor color scheme
        cs = opts / "colors.scheme.xml"
        scheme = t["jetbrains"]
        # if the plugin theme isn't installed, fall back to the bundled Darcula/Light
        installed = _jb_scheme_available(root, scheme)
        if not installed:
            scheme = "Darcula" if t["mode"] == "dark" else "Default"
        backup(cs)
        cs.write_text(
            '<application>\n  <component name="EditorColorsManagerImpl">\n'
            f'    <global_color_scheme name="{scheme}" />\n'
            '  </component>\n</application>\n', encoding="utf-8")
        # 2) IDE look and feel (frame chrome)
        laf = opts / "laf.xml"
        theme_id = ("ExperimentalDark", "/themes/expUIDark.theme.json") if t["mode"] == "dark" \
                   else ("ExperimentalLight", "/themes/expUILight.theme.json")
        backup(laf)
        laf.write_text(
            '<application>\n  <component name="LafManager" autodetect="false">\n'
            f'    <laf themeId="{theme_id[0]}" />\n'
            '  </component>\n</application>\n', encoding="utf-8")
        any_ok = True
        note = "" if installed else " (plugin missing, used bundled)"
        msgs.append(f"{root.name} -> {scheme}{note}")
    return any_ok, "; ".join(msgs)

def _jb_scheme_available(root: Path, scheme_name: str) -> bool:
    """Check bundled names and installed plugin jars/xml for the scheme."""
    if scheme_name in ("Darcula", "Default", "Dark", "High contrast", "Light"):
        return True
    # user-installed schemes
    for sub in ("colors", "settingsRepository"):
        d = root / sub
        if d.exists():
            for f in d.rglob("*.icls"):
                if scheme_name.lower().replace(" ", "") in f.stem.lower().replace(" ", ""):
                    return True
    # plugins dir
    if WIN:
        pl = Path(os.environ.get("APPDATA", HOME))/"JetBrains"/root.name/"plugins"
    elif MAC:
        pl = HOME/"Library"/"Application Support"/"JetBrains"/root.name/"plugins"
    else:
        pl = HOME/".local"/"share"/"JetBrains"/root.name
    if pl.exists():
        blob = " ".join(p.name.lower() for p in pl.rglob("*") if p.is_file())
        key = scheme_name.split()[0].lower()
        if key in blob:
            return True
    return False

