def apply_vscode(t, install_ext=True):
    dirs = _vscode_dirs()
    if not dirs:
        return False, "not installed"
    msgs = []
    for label, path, cli in dirs:
        try:
            data = _read_json_lenient(path)
        except Exception as e:
            msgs.append(f"{label}: unreadable settings.json ({e})")
            continue
        ext = t.get("vscode_ext")
        if install_ext and ext and which(cli):
            rc, out, _ = run([cli, "--list-extensions"])
            if rc == 0 and ext.lower() not in out.lower():
                run([cli, "--install-extension", ext, "--force"])
        data["workbench.colorTheme"] = t["vscode"]
        # terminal colors inside the editor follow the same palette
        p = t["palette"]
        cc = data.get("workbench.colorCustomizations") or {}
        cc.update({
            "terminal.background": t["bg"], "terminal.foreground": t["fg"],
            "terminalCursor.foreground": t["cursor"],
            "terminal.selectionBackground": t["selection_bg"],
            "terminal.ansiBlack": p[0], "terminal.ansiRed": p[1], "terminal.ansiGreen": p[2],
            "terminal.ansiYellow": p[3], "terminal.ansiBlue": p[4], "terminal.ansiMagenta": p[5],
            "terminal.ansiCyan": p[6], "terminal.ansiWhite": p[7],
            "terminal.ansiBrightBlack": p[8], "terminal.ansiBrightRed": p[9],
            "terminal.ansiBrightGreen": p[10], "terminal.ansiBrightYellow": p[11],
            "terminal.ansiBrightBlue": p[12], "terminal.ansiBrightMagenta": p[13],
            "terminal.ansiBrightCyan": p[14], "terminal.ansiBrightWhite": p[15],
        })
        data["workbench.colorCustomizations"] = cc
        data["window.autoDetectColorScheme"] = False
        backup(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(data, indent=2), encoding="utf-8")
        msgs.append(f"{label} -> {t['vscode']}")
    return True, "; ".join(msgs)

