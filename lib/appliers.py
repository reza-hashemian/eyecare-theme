def detect_available():
    """Return list of target names that look installed (cheap probe)."""
    found = []
    probes = {
        "alacritty": lambda: which("alacritty") or (HOME/".config"/"alacritty").exists(),
        "kitty": lambda: which("kitty") or (HOME/".config"/"kitty").exists(),
        "wezterm": lambda: which("wezterm") or (HOME/".config"/"wezterm").exists() or (HOME/".wezterm.lua").exists(),
        "gnome-terminal": lambda: bool(which("gnome-terminal")) and bool(which("gsettings")),
        "xfce4-terminal": lambda: which("xfce4-terminal") or (HOME/".config"/"xfce4"/"terminal").exists(),
        "konsole": lambda: which("konsole") or (HOME/".local"/"share"/"konsole").exists(),
        "windows-terminal": lambda: WIN,
        "iterm2": lambda: MAC and (HOME/"Library"/"Preferences"/"com.googlecode.iterm2.plist").exists(),
        "vscode": lambda: bool(_vscode_dirs()),
        "jetbrains": lambda: bool(_jetbrains_config_roots()),
        "neovim": lambda: which("nvim") or (HOME/".config"/"nvim").exists(),
        "gnome-desktop": lambda: bool(which("gsettings")) and "gnome" in (os.environ.get("XDG_CURRENT_DESKTOP","").lower()),
    }
    for name, fn in probes.items():
        try:
            if fn():
                found.append(name)
        except Exception:
            pass
    return found
